from __future__ import annotations

import itertools
import re
from pathlib import Path

import pytest

from platformctl import compose_files as cf
from platformctl import config as cfg
from platformctl.config import PlatformConfig
from platformctl.system import envfile


def make_root(tmp_path: Path) -> Path:
    root = tmp_path / "platform"
    for rel in (
        "agents/client-agent",
        "agents/form-filler-agent",
        "agents/debug-agents/thermal-agent",
        "agents/optional/osti-research-agent",
        "agents/no-compose",
    ):
        (root / rel).mkdir(parents=True)
        if rel != "agents/no-compose":
            (root / rel / "docker-compose.yml").write_text("services: {}\n")
    (root / "agents/client-agent/agent_card.json").write_text("{}")
    (root / "docker-compose.yml").write_text("services: {}\n")
    return root


def config_for(root: Path, **settings: str) -> PlatformConfig:
    return PlatformConfig(root, {}, settings)


def test_discover_in_tree_only_by_default(tmp_path):
    root = make_root(tmp_path)
    agents = cf.discover_agents(root, config_for(root))
    assert [(a.name, a.group) for a in agents] == [("client-agent", "in-tree"), ("form-filler-agent", "in-tree")]
    assert agents[0].card == root / "agents/client-agent/agent_card.json"
    assert agents[1].card is None


def test_discover_debug_and_optional(tmp_path):
    root = make_root(tmp_path)
    agents = cf.discover_agents(root, config_for(root, DEBUG_AGENTS="true", OPTIONAL_AGENTS="true"))
    assert [(a.name, a.group) for a in agents][2:] == [("thermal-agent", "debug"), ("osti-research-agent", "optional")]


def test_discover_with_no_agents_folder(tmp_path):
    root = tmp_path / "empty"
    root.mkdir()
    assert cf.discover_agents(root, config_for(root)) == []


@pytest.mark.parametrize(
    ("debug", "optional", "deeplynx", "testing", "override"),
    [(*flags, override) for flags in itertools.product(["false", "true"], repeat=4) for override in (False, True)],
)
def test_file_list_for_every_combination(tmp_path, debug, optional, deeplynx, testing, override):
    root = make_root(tmp_path)
    if override:
        (root / "docker-compose.override.yml").write_text("services: {}\n")
    config = config_for(
        root, DEBUG_AGENTS=debug, OPTIONAL_AGENTS=optional, LOCAL_DEEPLYNX=deeplynx, PROMETHEUS_SYSTEM_TESTING=testing
    )
    agents = cf.discover_agents(root, config)
    expected = ["docker-compose.yml"]
    if testing == "true":
        expected.append("docker-compose.system-test.yml")
    expected.append("docker-compose.agents.yml")
    if deeplynx == "true":
        expected.append("docker-compose.deeplynx.yml")
    if override:
        expected.append("docker-compose.override.yml")
    assert cf.compose_file_list(root, config, agents) == expected


def test_no_generate_includes_the_agents_file_only_if_it_exists(tmp_path):
    root = make_root(tmp_path)
    config = config_for(root)
    agents = cf.discover_agents(root, config)
    assert "docker-compose.agents.yml" not in cf.compose_file_list(root, config, agents, generated_agents=False)
    (root / "docker-compose.agents.yml").write_text("include: []\n")
    assert "docker-compose.agents.yml" in cf.compose_file_list(root, config, agents, generated_agents=False)


def test_no_agents_means_no_agents_file(tmp_path):
    root = make_root(tmp_path)
    assert cf.compose_file_list(root, config_for(root), []) == ["docker-compose.yml"]


def test_agents_file_content_is_pinned(tmp_path):
    root = make_root(tmp_path)
    agents = cf.discover_agents(root, config_for(root))
    assert cf.render_agents_file(root, agents) == (
        "# Generated by platformctl; do not edit. Rerun ./platformctl agents generate\n"
        "# after checking out or removing agent submodules.\n"
        "\n"
        "include:\n"
        "  - agents/client-agent/docker-compose.yml\n"
        "  - agents/form-filler-agent/docker-compose.yml\n"
    )


def test_entry_file_content_is_pinned():
    assert cf.render_entry_file("prometheus_platform", ["docker-compose.yml", "docker-compose.agents.yml"]) == (
        "# docker-compose.platform.yml\n"
        "# Generated by platformctl; do not edit. Rerun ./platformctl agents generate\n"
        "# after changing LOCAL_SDK, the base-image pin or the agents.\n"
        "name: prometheus_platform\n"
        "include:\n"
        "  - path: [docker-compose.yml, docker-compose.agents.yml]\n"
        "    env_file: [.platform.env]\n"
    )


def test_platform_env_content_is_pinned_and_parses_back():
    values = {
        "PROMETHEUS_API_BASE_IMAGE_REPO": "prometheus_api",
        "PROMETHEUS_API_BASE_IMAGE_HASH": "local",
        "USE_BUILD_CACHE": "false",
    }
    text = cf.render_platform_env(values)
    assert text.startswith("# Generated by platformctl; settings go in .env, not here.\n")
    assert envfile.parse(text) == values


def test_platform_env_refuses_a_key_that_is_not_marked_safe():
    for key in ("LLM_API_KEY", "UNREGISTERED"):
        with pytest.raises(ValueError, match="not marked safe"):
            cf.render_platform_env({key: "x"})


def test_platform_env_never_has_a_secret_key():
    """Every key the tool can derive is safe to print."""
    for key in (
        "PROMETHEUS_API_BASE_IMAGE_REPO",
        "PROMETHEUS_API_BASE_IMAGE_HASH",
        "BUILD_CACHE",
        "BUILD_CACHE_PLATFORM",
        "USE_BUILD_CACHE",
    ):
        assert cfg.is_safe(key)


def test_derived_values(tmp_path):
    root = make_root(tmp_path)
    off = cf.derived_values(config_for(root), build_cache=False, arch="arm64")
    assert off == {
        "PROMETHEUS_API_BASE_IMAGE_REPO": cfg.DEFAULT_BASE_IMAGE_REPO,
        "PROMETHEUS_API_BASE_IMAGE_HASH": cfg.DEFAULT_BASE_IMAGE_HASH,
        "USE_BUILD_CACHE": "false",
    }
    on = cf.derived_values(config_for(root, LOCAL_SDK="true"), build_cache=True, arch="arm64")
    assert on["PROMETHEUS_API_BASE_IMAGE_REPO"] == "prometheus_api"
    assert on["PROMETHEUS_API_BASE_IMAGE_HASH"] == "local"
    assert (on["BUILD_CACHE"], on["BUILD_CACHE_PLATFORM"], on["USE_BUILD_CACHE"]) == (
        cfg.DEFAULT_BUILD_CACHE,
        "arm64",
        "true",
    )
    pinned = cf.derived_values(config_for(root, BUILD_CACHE_PLATFORM="amd64"), build_cache=True, arch="arm64")
    assert pinned["BUILD_CACHE_PLATFORM"] == "amd64"


def test_write_generated_with_and_without_the_cache(tmp_path):
    root = make_root(tmp_path)
    config = config_for(root, PROMETHEUS_SYSTEM_TESTING="true", COMPOSE_PROJECT_NAME="second")
    agents = cf.discover_agents(root, config)
    written = cf.write_generated(root, config, agents, build_cache=True, arch="amd64")
    assert set(written) == {"entry", "env", "agents"}
    entry = written["entry"].read_text()
    assert "name: second\n" in entry
    assert re.search(
        r"path: \[docker-compose.yml, docker-compose.system-test.yml, docker-compose.agents.yml, docker-compose.build-cache.yml\]",
        entry,
    )
    assert "BUILD_CACHE_PLATFORM=amd64" in written["env"].read_text()
    written = cf.write_generated(root, config, agents, build_cache=False, arch="amd64")
    assert "build-cache" not in written["entry"].read_text()
    assert "BUILD_CACHE" not in written["env"].read_text().replace("USE_BUILD_CACHE", "")


def test_write_generated_without_agents_or_without_regenerating(tmp_path):
    root = make_root(tmp_path)
    config = config_for(root)
    written = cf.write_generated(root, config, [], build_cache=False, arch="amd64")
    assert "agents" not in written and not (root / "docker-compose.agents.yml").exists()
    agents = cf.discover_agents(root, config)
    written = cf.write_generated(root, config, agents, build_cache=False, arch="amd64", generated_agents=False)
    assert "agents" not in written and not (root / "docker-compose.agents.yml").exists()
