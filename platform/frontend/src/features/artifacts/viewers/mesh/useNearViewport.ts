import { useEffect, useState, type RefObject } from "react";

/** True once `ref`'s element has come within `margin` of the viewport, and from then on.
 *
 * Without `IntersectionObserver` (jsdom, very old browsers) it is true at once, so a
 * viewer degrades to loading eagerly rather than never. */
export function useNearViewport(ref: RefObject<Element | null>, margin = "200px"): boolean {
  const [near, setNear] = useState(() => typeof IntersectionObserver === "undefined");

  useEffect(() => {
    if (near) return;
    const el = ref.current;
    if (!el) return;
    const observer = new IntersectionObserver(
      (entries) => {
        if (entries.some((e) => e.isIntersecting)) {
          setNear(true);
          observer.disconnect();
        }
      },
      { rootMargin: margin },
    );
    observer.observe(el);
    return () => observer.disconnect();
  }, [near, ref, margin]);

  return near;
}
